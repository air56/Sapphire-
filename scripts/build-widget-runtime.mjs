import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const scriptRoot = dirname(fileURLToPath(import.meta.url));
const widgetRoot = join(scriptRoot, '..', 'widgets', 'netease-lyrics-glass');
const metadata = JSON.parse(await readFile(join(widgetRoot, 'metadata.json'), 'utf8'));
const version = String(metadata.version).trim();
const sources = [
  'settings.js',
  'lyric-view-model.js',
  'preview-mode.js',
  'responsive-layout.js',
  'sapphire-smtc.js',
  'app.js'
];

const chunks = [];
for (const file of sources) {
  let source = await readFile(join(widgetRoot, file), 'utf8');
  if (file !== 'app.js') {
    source = source.replace(/^export\s+/gm, '');
  } else {
    source = source.replace(/^import[^;]+;\s*$/gm, '');
  }
  chunks.push(`/* --- ${file} --- */\n${source.trim()}`);
}

const banner = `/* Generated classic-script runtime for Sapphire WebEngine.\n * Source of truth: app.js and the helper modules next to it.\n * Do not edit this file by hand; package-widget.ps1 regenerates it.\n */\n(function markNeteaseLyricsRuntime() {\n  document.documentElement.dataset.neteaseLyricsRuntime = '${version}';\n  window.__neteaseLyricsRuntime = { version: '${version}', started: true, bridgeConnected: false };\n})();\n`;
await writeFile(join(widgetRoot, 'app.runtime.js'), `${banner}\n${chunks.join('\n\n')}\n`, 'utf8');
